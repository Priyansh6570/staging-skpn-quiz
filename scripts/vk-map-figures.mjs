// Maps the native images pdfimages pulled out of po.pdf onto printed page numbers.
//
// PDF page N is a spread holding printed 2N+26 (left) and 2N+27 (right). pdfimages reports no
// placement, so the side is inferred from the page classification: if only one of the two halves
// carries imagery, every image on that PDF page belongs to it. Where both halves do, the images are
// listed as ambiguous rather than guessed.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const RAW = join(ROOT, "figures-raw");

const kinds = new Map(
  JSON.parse(readFileSync(join(ROOT, "vk-pages.json"), "utf8")).map((p) => [p.printed, p.kind]),
);

// A smask is the alpha channel of the image before it, not a figure. They are greyscale and tiny
// next to their partner, so size is the reliable discriminator here.
const files = readdirSync(RAW).filter((f) => f.endsWith(".jpg")).sort();
const rows = files.map((f) => {
  const [, pdfPage, idx] = f.match(/^fig-(\d+)-(\d+)\.jpg$/);
  return { file: f, pdfPage: Number(pdfPage), idx: Number(idx), bytes: statSync(join(RAW, f)).size };
});

const byPage = new Map();
for (const r of rows) {
  if (!byPage.has(r.pdfPage)) byPage.set(r.pdfPage, []);
  byPage.get(r.pdfPage).push(r);
}

const hasArt = (printed) => kinds.get(printed) === "plate-fullbleed" || kinds.get(printed) === "plate-inset" || kinds.get(printed) === "mixed";

const out = { $comment: "Generated by scripts/vk-map-figures.mjs. Native encodes from po.pdf, no re-render and no upscale. Keyed by printed page.", byPrintedPage: {}, ambiguous: [], unplaced: [] };

for (const [pdfPage, list] of [...byPage].sort((a, b) => a[0] - b[0])) {
  const left = pdfPage * 2 + 26, right = pdfPage * 2 + 27;
  const candidates = [left, right].filter(hasArt);
  const entry = list.map((r) => ({ file: r.file, bytes: r.bytes }));

  if (candidates.length === 1) {
    out.byPrintedPage[candidates[0]] = (out.byPrintedPage[candidates[0]] ?? []).concat(entry);
  } else if (candidates.length === 2) {
    out.ambiguous.push({ pdfPage, printedPages: [left, right], files: entry.map((e) => e.file) });
  } else {
    out.unplaced.push({ pdfPage, printedPages: [left, right], kinds: [kinds.get(left), kinds.get(right)], files: entry.map((e) => e.file) });
  }
}

writeFileSync(join(ROOT, "vk-figures.json"), `${JSON.stringify(out, null, 2)}\n`);

const placed = Object.values(out.byPrintedPage).flat().length;
const ambig = out.ambiguous.flatMap((a) => a.files).length;
const unpl = out.unplaced.flatMap((a) => a.files).length;
console.log(`files: ${rows.length}`);
console.log(`placed on a single printed page: ${placed} across ${Object.keys(out.byPrintedPage).length} pages`);
console.log(`ambiguous (both halves carry art): ${ambig} across ${out.ambiguous.length} spreads`);
console.log(`unplaced (neither half classified as art): ${unpl} across ${out.unplaced.length} spreads`);
