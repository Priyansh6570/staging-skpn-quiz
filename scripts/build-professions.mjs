// Optimises the eight approved profession illustrations into public/professions/.
//
// The artwork is used as it is — no crop, no recolour, no overlay. Each source is re-encoded to
// WebP at a set of widths for a responsive srcset, and **never above its own width**: sharp is given
// withoutEnlargement, and any requested width past the source is dropped rather than upscaled.
//
//   node scripts/build-professions.mjs

import { readdirSync, mkdirSync, writeFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { PROFESSIONS } from "../lib/i18n/professions.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "design", "professions");
const OUT = join(ROOT, "public", "professions");

/** The widths the section actually renders at: one column on a phone, two up, then the wide grid. */
const WIDTHS = [480, 768, 1074];
const QUALITY = 82;

const available = new Set(readdirSync(SRC).filter((f) => /\.(jpe?g|png)$/i.test(f)).map((f) => f.replace(/\.[^.]+$/, "")));
const missing = PROFESSIONS.map((p) => p.key).filter((k) => !available.has(k));
if (missing.length) {
  console.error(`refusing: no artwork for ${missing.join(", ")} in design/professions`);
  process.exit(1);
}

mkdirSync(OUT, { recursive: true });

const manifest = {};
let srcBytes = 0;
let outBytes = 0;
/** What a wide screen actually downloads: the largest variant of each, against its source. */
let widestBytes = 0;

for (const { key } of PROFESSIONS) {
  const file = readdirSync(SRC).find((f) => f.replace(/\.[^.]+$/, "") === key);
  const from = join(SRC, file);
  srcBytes += statSync(from).size;

  const meta = await sharp(from).metadata();
  // Never past the source, and never two sizes a handful of pixels apart: these sources are 1074 or
  // 1075 wide, so appending the native width blindly emitted a second near-identical file.
  const widths = WIDTHS.filter((w) => w <= meta.width);
  if (!widths.some((w) => meta.width - w < 16)) widths.push(meta.width);

  const sources = [];
  for (const w of widths) {
    const info = await sharp(from)
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: QUALITY })
      .toFile(join(OUT, `${key}-${w}.webp`));
    outBytes += info.size;
    if (w === widths.at(-1)) widestBytes += info.size;
    sources.push({ width: info.width, src: `/professions/${key}-${w}.webp` });
  }

  manifest[key] = { width: meta.width, height: meta.height, sources };
}

writeFileSync(join(ROOT, "professions.json"), `${JSON.stringify({
  $comment: "Generated by scripts/build-professions.mjs from design/professions. Widths never exceed"
    + " the source. Read by components/ProfessionBridge.tsx for its srcset.",
  images: manifest,
}, null, 2)}\n`);

const mb = (b) => `${(b / 1024 / 1024).toFixed(1)}MB`;
console.log(`${PROFESSIONS.length} illustrations -> public/professions/ at ${WIDTHS.join(", ")}px`);
console.log(`widest variant of each: ${mb(srcBytes)} jpeg -> ${mb(widestBytes)} webp`
  + `  (${Math.round((1 - widestBytes / srcBytes) * 100)}% smaller)`);
console.log(`${mb(outBytes)} on disk across every size; a phone loads the 480 of one, not all of them.`);
